    def _send_registration_notification(self, property_rec, registration, registered_count, exempted_count):
        template = self.env.ref('pms_l10n_it.email_template_registration_notification', False)
        if template:
            template.with_context(
                registered_count=registered_count,
                exempted_count=exempted_count,
                property_name=property_rec.name,
                registration_id=registration.id
            ).send_mail(property_rec.id)

    @api.model
    def _cron_auto_guest_registration(self):
        properties = self.search([
            ('it_guest_registration_enabled', '=', True),
            ('auto_register_checkin', '=', True)
        ])
        current_time = fields.Datetime.now()
        current_hour_minute = current_time.strftime('%H:%M')
        for property_rec in properties:
            try:
                target_time = property_rec.auto_register_time
                if target_time and current_hour_minute == target_time:
                    guests_to_register = property_rec.get_guests_for_auto_registration()
                    if guests_to_register:
                        exempted_guests = self.env['pms.checkin.partner']
                        for guest in guests_to_register:
                            if guest.birthdate_date:
                                age = (fields.Date.today() - guest.birthdate_date).days / 365.25
                                if age < property_rec.exempt_minors_under_age:
                                    guest.write({
                                        'it_exemption_reason': 'minor',
                                        'it_exemption_notes': _('Auto-exempted: Minor under %s years') % property_rec.exempt_minors_under_age
                                    })
                                    exempted_guests |= guest
                        guests_to_register -= exempted_guests
                        if guests_to_register:
                            registration = self.env['pms.guest.registration'].create({
                                'property_id': property_rec.id,
                                'registration_date': fields.Date.today(),
                                'checkin_partner_ids': [(6, 0, guests_to_register.ids)],
                            })
                            try:
                                registration.action_send_registration()
                                _logger.info(
                                    "Auto-registration successful for property %s: %d guests registered, %d exempted",
                                    property_rec.name,
                                    len(guests_to_register),
                                    len(exempted_guests)
                                )
                                if property_rec.registration_notification_emails:
                                    self._send_registration_notification(
                                        property_rec,
                                        registration,
                                        len(guests_to_register),
                                        len(exempted_guests)
                                    )
                            except Exception as e:
                                _logger.error(
                                    "Auto-registration failed for property %s: %s",
                                    property_rec.name, str(e)
                                )
                                registration.write({
                                    'state': 'error',
                                    'error_message': str(e)
                                })
            except Exception as e:
                _logger.error(
                    "Error in auto-registration cron for property %s: %s",
                    property_rec.name, str(e)
                )

    @api.model
    def _cron_send_remote_checkin_reminders(self):
        properties = self.search([
            ('remote_checkin_enabled', '=', True),
            ('remote_checkin_reminder_hours', '>', 0)
        ])
        for property_rec in properties:
            try:
                reminder_time = fields.Datetime.now() + timedelta(hours=property_rec.remote_checkin_reminder_hours)
                tokens = self.env['pms.remote.checkin.token'].search([
                    ('property_id', '=', property_rec.id),
                    ('state', '=', 'sent'),
                    ('reservation_id.checkin', '<=', reminder_time),
                    ('expires_at', '>', fields.Datetime.now())
                ])
                for token in tokens:
                    if not hasattr(token, 'reminder_sent') or not token.reminder_sent:
                        token._send_reminder_email()
            except Exception as e:
                _logger.error(
                    "Error sending remote check-in reminders for property %s: %s",
                    property_rec.name, str(e)
                )

    @api.model
    def _cron_cleanup_old_data(self):
        properties = self.search([('it_guest_registration_enabled', '=', True)])
        for property_rec in properties:
            try:
                if property_rec.auto_download_receipts and property_rec.receipt_retention_days > 0:
                    property_rec.action_cleanup_old_receipts()
                expired_tokens = self.env['pms.remote.checkin.token'].search([
                    ('property_id', '=', property_rec.id),
                    ('expires_at', '<', fields.Datetime.now()),
                    ('state', '!=', 'expired')
                ])
                expired_tokens.write({'state': 'expired'})
                old_checkin_data = self.env['pms.remote.checkin.data'].search([
                    ('token_id.property_id', '=', property_rec.id),
                    ('create_date', '<', fields.Datetime.now() - timedelta(days=365))
                ])
                old_checkin_data.unlink()
            except Exception as e:
                _logger.error(
                    "Error cleaning up old data for property %s: %s",
                    property_rec.name, str(e)
                )
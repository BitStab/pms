    def action_send_remote_checkin_links(self):
        self.ensure_one()
        if not self.remote_checkin_enabled:
            raise UserError(_("Remote check-in is not enabled for this property"))
        arrival_window_start = fields.Datetime.now()
        arrival_window_end = arrival_window_start + timedelta(hours=self.remote_checkin_hours_before)
        reservations = self.env['pms.reservation'].search([
            ('pms_property_id', '=', self.id),
            ('checkin', '>=', arrival_window_start),
            ('checkin', '<=', arrival_window_end),
            ('state', 'in', ['confirm', 'onboard'])
        ])
        sent_count = 0
        for reservation in reservations:
            if reservation.partner_id and reservation.partner_id.email:
                try:
                    existing_token = self.env['pms.remote.checkin.token'].search([
                        ('reservation_id', '=', reservation.id),
                        ('state', 'in', ['sent', 'accessed']),
                        ('expires_at', '>', fields.Datetime.now())
                    ])
                    if not existing_token:
                        token = self.env['pms.remote.checkin.token'].generate_token_for_reservation(
                            reservation.id,
                            reservation.partner_id.email
                        )
                        sent_count += 1
                except Exception as e:
                    _logger.error(
                        "Failed to send remote check-in link for reservation %s: %s",
                        reservation.name, str(e)
                    )
        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'title': _('Remote Check-in Links Sent'),
                'message': _('%d remote check-in links sent successfully') % sent_count,
                'type': 'success',
            }
        }

    def action_cleanup_old_receipts(self):
        self.ensure_one()
        if self.receipt_retention_days <= 0:
            return
        cutoff_date = fields.Date.today() - timedelta(days=self.receipt_retention_days)
        old_receipts = self.env['pms.guest.registration.receipt'].search([
            ('property_id', '=', self.id),
            ('receipt_date', '<', cutoff_date)
        ])
        deleted_count = len(old_receipts)
        old_receipts.unlink()
        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'title': _('Cleanup Complete'),
                'message': _('%d old receipts deleted') % deleted_count,
                'type': 'info',
            }
        }


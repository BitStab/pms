    @api.constrains('auto_register_time')
    def _check_auto_register_time(self):
        """Validate time format"""
        for record in self:
            if record.auto_register_time:
                import re
                time_pattern = r'^([01]?[0-9]|2[0-3]):[0-5][0-9]$'
                if not re.match(time_pattern, record.auto_register_time):
                    raise ValidationError(_("Invalid time format. Please use HH:MM format (e.g., 23:00)"))


    @api.depends('registration_count')
    def _compute_registration_stats(self):
        for record in self:
            successful_registrations = self.env['pms.guest.registration'].search([
                ('property_id', '=', record.id),
                ('state', '=', 'sent')
            ])
            record.total_guests_registered = sum(successful_registrations.mapped('guest_count'))
            record.last_successful_registration = max(
                successful_registrations.mapped('transmission_date'),
                default=False
            )
            failed_registrations = self.env['pms.guest.registration'].search_count([
                ('property_id', '=', record.id),
                ('state', '=', 'error')
            ])
            record.failed_registrations_count = failed_registrations

    @api.model
    def get_guests_for_auto_registration(self, date_from=None, date_to=None):
        self.ensure_one()
        if not date_from:
            date_from = fields.Date.today()
        if not date_to:
            date_to = date_from
        domain = [
            ('arrival', '>=', date_from),
            ('arrival', '<=', date_to),
            ('state', '=', 'onboard'),
            ('it_registered', '=', False),
        ]
        if 'pms_property_id' in self.env['pms.checkin.partner']._fields:
            domain.append(('pms_property_id', '=', self.id))
        elif 'property_id' in self.env['pms.checkin.partner']._fields:
            domain.append(('property_id', '=', self.id))
        else:
            reservations = self.env['pms.reservation'].search([
                ('pms_property_id', '=', self.id),
                ('state', 'in', ['onboard', 'confirm']),
            ])
            domain.append(('reservation_id', 'in', reservations.ids))
        if self.auto_select_criteria == 'adults_only':
            min_birthdate = fields.Date.today() - timedelta(days=18*365.25)
            domain.append(('birthdate_date', '<=', min_birthdate))
        elif self.auto_select_criteria == 'non_exempt':
            domain.append(('it_exemption_reason', '=', False))
        elif self.auto_select_criteria == 'by_nationality':
            if self.auto_select_nationalities:
                domain.append(('nationality_id', 'in', self.auto_select_nationalities.ids))
        if self.auto_register_delay_hours > 0:
            delay_datetime = fields.Datetime.now() - timedelta(hours=self.auto_register_delay_hours)
            domain.append(('checkin', '<=', delay_datetime))
        return self.env['pms.checkin.partner'].search(domain)

    @api.constrains('alloggiati_web_username', 'alloggiati_web_password', 'alloggiati_web_codice_struttura', 'alloggiati_web_wskey')
    def _check_alloggiati_web_config(self):
        for record in self:
            if record.it_guest_registration_enabled:
                if not record.alloggiati_web_username:
                    raise ValidationError(_("Username is required for Alloggiati Web"))
                if not record.alloggiati_web_password:
                    raise ValidationError(_("Password is required for Alloggiati Web"))
                if not record.alloggiati_web_codice_struttura:
                    raise ValidationError(_("Codice Struttura is required for Alloggiati Web"))
                if not record.alloggiati_web_wskey:
                    raise ValidationError(_("WS Key is required for Alloggiati Web"))

    @api.constrains('remote_checkin_hours_before', 'remote_checkin_reminder_hours')
    def _check_remote_checkin_timing(self):
        for record in self:
            if record.remote_checkin_enabled:
                if record.remote_checkin_hours_before < 1:
                    raise ValidationError(_("Remote check-in must be available at least 1 hour before arrival"))
                if record.remote_checkin_reminder_hours > record.remote_checkin_hours_before:
                    raise ValidationError(_("Reminder cannot be sent after remote check-in becomes available"))

